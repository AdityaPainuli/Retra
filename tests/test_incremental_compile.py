"""The nightly wiki compile only spends an LLM call when the day's note
changed, and only sends the pages that note mentions."""

import fcntl
import shutil
from datetime import date

import pytest

from config.settings import ObsidianConfig, Settings
from export import pipeline_status, wiki_compiler, wiki_history

DAY = date(2026, 11, 5)
NOTE = "# Thu\nWorked on retra and the chatty-cortex backend.\n\n*Generated by Retra at 23:00*\n"

pytestmark = pytest.mark.skipif(shutil.which("git") is None, reason="git not installed")


@pytest.fixture
def compiler(tmp_path, monkeypatch):
    from config import settings as settings_mod
    vault = tmp_path / "vault"
    settings = Settings(obsidian=ObsidianConfig(vault_path=str(vault)))
    settings.obsidian.output_dir.mkdir(parents=True)
    wiki = vault / "retra-wiki"
    for d in ("projects", "people", "rollups"):
        (wiki / d).mkdir(parents=True)
    (wiki / "CLAUDE.md").write_text("schema\n")
    (wiki / "projects" / "retra.md").write_text("# Retra\nRETRA BODY\n")
    (wiki / "projects" / "chatty-insights.md").write_text(
        "---\ntitle: Chatty\naliases: [chatty-cortex, chatty-backend]\n---\n# Chatty\nCHATTY BODY\n")
    (wiki / "rollups" / "2026-w44.md").write_text("# Week 44\nROLLUP BODY\n")

    monkeypatch.setattr(settings_mod, "_settings", settings)
    monkeypatch.setattr(wiki_compiler, "COMPILE_STATE_PATH", tmp_path / "wiki_compiles.json")
    monkeypatch.setattr(wiki_history, "WIKI_GIT_DIR", tmp_path / "wiki.git")
    monkeypatch.setattr(wiki_history, "WIKI_LOCK_PATH", tmp_path / "wiki.lock")
    monkeypatch.setattr(pipeline_status, "PIPELINE_STATUS_PATH", tmp_path / "pipeline.json")

    prompts, replies = [], []
    monkeypatch.setattr(wiki_compiler, "_call_claude", lambda p: prompts.append(p) or (replies.pop(0) if replies else ""))

    class C:
        note = settings.obsidian.output_dir / f"{DAY.isoformat()}.md"

        def run(self, note=NOTE, reply="===FILE: projects/retra.md===\n# Retra\nupdated\n===END_FILE===\n",
                day=DAY, **kw):
            path = settings.obsidian.output_dir / f"{day.isoformat()}.md"
            path.write_text(note)
            replies.append(reply)
            wiki_compiler.compile_daily_note(day, **kw)

    c = C()
    c.wiki, c.prompts = wiki, prompts
    return c


def test_unchanged_note_is_not_compiled_again(compiler):
    compiler.run()
    compiler.run(note=NOTE.replace("23:00", "23:41"))  # only the footer changed
    assert len(compiler.prompts) == 1

    compiler.run(note=NOTE + "Also reviewed a PR.\n")
    assert len(compiler.prompts) == 2

    compiler.run(note=NOTE + "Also reviewed a PR.\n", force=True)
    assert len(compiler.prompts) == 3


def test_failed_compile_is_retried(compiler):
    compiler.run(reply=None)
    compiler.run()
    assert len(compiler.prompts) == 2


def test_sends_only_pages_the_note_mentions(compiler):
    compiler.run()
    prompt = compiler.prompts[0]
    assert "RETRA BODY" in prompt
    assert "CHATTY BODY" in prompt, "matched through its chatty-cortex alias"
    assert "ROLLUP BODY" not in prompt
    assert "  - rollups/2026-w44.md" in prompt, "unsent pages are still listed by name"


def test_pages_it_was_not_shown_are_not_rewritten(compiler):
    reply = ("===FILE: rollups/2026-w44.md===\n# Week 44\nguessed\n===END_FILE===\n"
             "===FILE: people/matteo.md===\n# Matteo\n===END_FILE===\n")
    compiler.run(reply=reply)
    assert "ROLLUP BODY" in (compiler.wiki / "rollups" / "2026-w44.md").read_text()
    assert (compiler.wiki / "people" / "matteo.md").exists(), "new pages are still written"


def test_prompt_stays_flat_as_unrelated_pages_grow(compiler):
    compiler.run()
    for i in range(50):
        (compiler.wiki / "rollups" / f"old-{i}.md").write_text("# Old\n" + "filler " * 500)
    compiler.run(force=True)
    small, big = map(len, compiler.prompts)
    assert big - small < 50 * 60, "only the names of unrelated pages are added"


def test_short_or_partial_names_do_not_match():
    assert not wiki_compiler._mentions("worked on retrace", "retra")
    assert wiki_compiler._mentions("chatty cortex sync", "chatty-cortex")
    assert not wiki_compiler._mentions("ai stuff", "ai")


def test_malformed_reply_is_not_cached(compiler):
    compiler.run(reply="===FILE: projects/retra.md===\n# Retra\ncut off before the end marker")
    compiler.run()
    assert len(compiler.prompts) == 2
    assert "RETRA BODY" not in (compiler.wiki / "projects" / "retra.md").read_text()


def test_hash_is_saved_while_the_wiki_lock_is_held(compiler, monkeypatch):
    held = []
    save = wiki_compiler._save_compile_entry

    def checking_save(*a, **kw):
        with wiki_history.WIKI_LOCK_PATH.open("w") as fh:
            try:
                fcntl.flock(fh, fcntl.LOCK_EX | fcntl.LOCK_NB)
                fcntl.flock(fh, fcntl.LOCK_UN)
                held.append(False)
            except BlockingIOError:
                held.append(True)
        save(*a, **kw)

    monkeypatch.setattr(wiki_compiler, "_save_compile_entry", checking_save)
    compiler.run()
    assert held == [True]


def test_failed_sunday_rollup_is_retried_without_redoing_the_ingest(compiler, monkeypatch):
    sunday = date(2026, 11, 8)
    results = [False, True]
    calls = []
    monkeypatch.setattr(wiki_compiler, "compile_week", lambda d: calls.append(d) or results.pop(0))

    compiler.run(day=sunday)  # ingest ok, rollup fails
    compiler.run(day=sunday)  # unchanged note: no ingest, rollup retried and ok
    compiler.run(day=sunday)  # nothing left to do
    assert len(compiler.prompts) == 1
    assert calls == [sunday, sunday]


def test_aliases_in_every_frontmatter_form():
    names = wiki_compiler._page_names
    assert "chatty-cortex" in names("projects/chatty-insights.md", "---\naliases: chatty-cortex\n---\n")
    assert {"a", "b"} <= names("projects/x.md", "---\naliases: [a, b]\n---\n")
    assert {"a", "b"} <= names("projects/x.md", "---\naliases:\n  - a\n  - b\ntags: [t]\n---\n")
    assert "t" not in names("projects/x.md", "---\naliases:\n  - a\ntags: [t]\n---\n")
